/**
 * Returns localized text for any of the 31 Census Questions
 */
export function getLocalizedQuestion(q: CensusQuestionSchema, langCode: string): LocalizedQuestion {
  const transObj = ALL_31_QUESTIONS_MAP[q.id];
  const catTrans = CATEGORY_TRANSLATIONS[q.category]?.[langCode] || q.category;

  if (transObj && transObj[langCode]) {
    return {
      id: q.id,
      number: q.number,
      label: transObj[langCode].label,
      description: transObj[langCode].description,
      whyAsked: transObj[langCode].whyAsked,
      category: catTrans,
    };
  }

  // If language is Hindi-family (mai, sa) and no direct entry, use Hindi
  if ((langCode === "mai" || langCode === "sa") && transObj?.hi) {
    return {
      id: q.id,
      number: q.number,
      label: transObj.hi.label,
      description: transObj.hi.description,
      whyAsked: transObj.hi.whyAsked,
      category: catTrans,
    };
  }

  // If language is Assamese and no direct entry, use Bengali
  if (langCode === "as" && transObj?.bn) {
    return {
      id: q.id,
      number: q.number,
      label: transObj.bn.label,
      description: transObj.bn.description,
      whyAsked: transObj.bn.whyAsked,
      category: catTrans,
    };
  }

  return {
    id: q.id,
    number: q.number,
    label: q.label,
    description: q.description,
    whyAsked: q.whyAsked,
    category: catTrans,
  };
}

