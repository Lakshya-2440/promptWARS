export function getLocalizedMyth(m: MythFactItem, langCode: string): LocalizedMyth {
  const trans = MYTH_TRANSLATIONS[m.id];
  if (trans && trans[langCode]) {
    return {
      id: m.id,
      category: trans[langCode].category,
      myth: trans[langCode].myth,
      fact: trans[langCode].fact,
      officialRef: m.officialRef
    };
  }
  if ((langCode === "mai" || langCode === "sa") && trans?.hi) {
    return {
      id: m.id,
      category: trans.hi.category,
      myth: trans.hi.myth,
      fact: trans.hi.fact,
      officialRef: m.officialRef
    };
  }
  return {
    id: m.id,
    category: m.category,
    myth: m.myth,
    fact: m.fact,
    officialRef: m.officialRef
  };
}

